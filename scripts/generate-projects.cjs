const fs = require('fs');
const path = require('path');
const matter = require('gray-matter');

const PROJECTS_DIR = path.join(__dirname, '../public/projects');
const OUTPUT_FILE = path.join(__dirname, '../src/data/generated_projects.ts');

// Ensure projects directory exists
if (!fs.existsSync(PROJECTS_DIR)) {
  console.error(`Directory not found: ${PROJECTS_DIR}`);
  process.exit(1);
}

function scanProjects() {
  const files = fs.readdirSync(PROJECTS_DIR);
  const projects = [];

  files.forEach(file => {
    if (!file.endsWith('.md')) return;

    const filePath = path.join(PROJECTS_DIR, file);
    const fileContent = fs.readFileSync(filePath, 'utf8');
    const { data } = matter(fileContent);

    // Construct project object matching the structure in src/types.ts
    const project = {
      id: data.id,
      star: data.star || false,
      common: {
        category: data.category,
        image: data.image || '',
        icon: data.icon,
        websiteUrl: data.websiteUrl,
        githubUrl: data.githubUrl
      },
      zh: {
        title: data.title_zh,
        subtitle: data.subtitle_zh,
        description: data.description_zh,
        role: data.role_zh,
        tags: data.tags_zh || [],
        roleDetail: data.roleDetail_zh
      },
      en: {
        title: data.title_en,
        subtitle: data.subtitle_en,
        description: data.description_en,
        role: data.role_en,
        tags: data.tags_en || [],
        roleDetail: data.roleDetail_en
      }
    };

    projects.push(project);
  });

  return projects;
}

const projects = scanProjects();

const fileContent = `// This file is auto-generated by scripts/generate-projects.cjs
// Do not edit this file directly.
// Edit the markdown files in projects/ instead.

import { Project } from '../types';

export const GENERATED_PROJECTS: Project[] = ${JSON.stringify(projects, null, 2)};
`;

fs.writeFileSync(OUTPUT_FILE, fileContent);

console.log(`Successfully generated ${projects.length} projects to ${OUTPUT_FILE}`);
