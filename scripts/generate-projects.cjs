const fs = require('fs');
const path = require('path');
const matter = require('gray-matter');

const PROJECTS_DIR = path.join(__dirname, '../public/projects');
const OUTPUT_DEV_FILE = path.join(__dirname, '../src/data/dev.ts');
const OUTPUT_DESIGN_FILE = path.join(__dirname, '../src/data/design.ts');

// Ensure projects directory exists
if (!fs.existsSync(PROJECTS_DIR)) {
  console.error(`Directory not found: ${PROJECTS_DIR}`);
  process.exit(1);
}

function scanProjects() {
  const files = fs.readdirSync(PROJECTS_DIR);
  const devProjects = [];
  const designProjects = [];

  files.forEach(file => {
    if (!file.endsWith('.md')) return;

    const filePath = path.join(PROJECTS_DIR, file);
    const fileContent = fs.readFileSync(filePath, 'utf8');
    const { data } = matter(fileContent);

    // Construct project object matching the structure in types.ts
    const project = {
      id: data.id,
      star: data.star || false,
      common: {
        category: data.category,
        image: data.image || '',
        ...(data.icon && { icon: data.icon }),
        ...(data.websiteUrl && { websiteUrl: data.websiteUrl }),
        ...(data.githubUrl && { githubUrl: data.githubUrl }),
        ...(data.figmaUrl && { figmaUrl: data.figmaUrl }),
        ...(data.gallery && { gallery: data.gallery })
      },
      zh: {
        title: data.title_zh,
        subtitle: data.subtitle_zh,
        description: data.description_zh,
        role: data.role_zh,
        tags: data.tags_zh || [],
        ...(data.roleDetail_zh && { roleDetail: data.roleDetail_zh }),
        ...(data.concept_zh && { concept: data.concept_zh }),
        ...(data.awards_zh && { awards: data.awards_zh })
      },
      en: {
        title: data.title_en,
        subtitle: data.subtitle_en,
        description: data.description_en,
        role: data.role_en,
        tags: data.tags_en || [],
        ...(data.roleDetail_en && { roleDetail: data.roleDetail_en }),
        ...(data.concept_en && { concept: data.concept_en }),
        ...(data.awards_en && { awards: data.awards_en })
      }
    };

    // Categorize projects
    if (data.category === 'Development') {
      devProjects.push(project);
    } else if (data.category === 'Graphics & UI') {
      designProjects.push(project);
    }
  });

  // Sort projects by id
  devProjects.sort((a, b) => a.id.localeCompare(b.id));
  designProjects.sort((a, b) => a.id.localeCompare(b.id));

  return { devProjects, designProjects };
}

function formatProjectObject(project) {
  const lines = ['  {'];
  lines.push(`    id: '${project.id}',`);
  if (project.star !== undefined) {
    lines.push(`    star: ${project.star},`);
  }
  lines.push('    common: {');
  lines.push(`      category: '${project.common.category}',`);
  lines.push(`      image: '${project.common.image}',`);

  // Optional common fields
  if (project.common.icon) lines.push(`      icon: '${project.common.icon}',`);
  if (project.common.websiteUrl) lines.push(`      websiteUrl: '${project.common.websiteUrl}',`);
  if (project.common.githubUrl) lines.push(`      githubUrl: '${project.common.githubUrl}',`);
  if (project.common.figmaUrl) lines.push(`      figmaUrl: '${project.common.figmaUrl}',`);
  if (project.common.gallery) {
    lines.push(`      gallery: [`);
    project.common.gallery.forEach(item => {
      lines.push(`        '${item}',`);
    });
    lines.push(`      ],`);
  }

  lines.push('    },');
  lines.push('    zh: {');
  lines.push(`      title: '${project.zh.title}',`);
  lines.push(`      subtitle: '${project.zh.subtitle}',`);
  lines.push(`      description: '${project.zh.description}',`);
  lines.push(`      role: '${project.zh.role}',`);
  lines.push(`      tags: [${project.zh.tags.map(t => `'${t}'`).join(', ')}],`);
  if (project.zh.roleDetail) lines.push(`      roleDetail: "${project.zh.roleDetail}",`);
  if (project.zh.concept) lines.push(`      concept: "${project.zh.concept}",`);
  if (project.zh.awards) {
    lines.push(`      awards: [${project.zh.awards.map(a => `'${a}'`).join(', ')}],`);
  }
  lines.push('    },');
  lines.push('    en: {');
  lines.push(`      title: '${project.en.title}',`);
  lines.push(`      subtitle: '${project.en.subtitle}',`);
  lines.push(`      description: '${project.en.description}',`);
  lines.push(`      role: '${project.en.role}',`);
  lines.push(`      tags: [${project.en.tags.map(t => `'${t}'`).join(', ')}],`);
  if (project.en.roleDetail) lines.push(`      roleDetail: "${project.en.roleDetail}",`);
  if (project.en.concept) lines.push(`      concept: "${project.en.concept}",`);
  if (project.en.awards) {
    lines.push(`      awards: [${project.en.awards.map(a => `'${a}'`).join(', ')}],`);
  }
  lines.push('    }');
  lines.push('  }');
  return lines.join('\n');
}

const { devProjects, designProjects } = scanProjects();

// Generate dev.ts
const devContent = `// This file is auto-generated by scripts/generate-projects.cjs
// Do not edit this file directly.
// Edit the markdown files in public/projects/ instead.

import { Project } from '../../types';

export const DEV_DATA: Project[] = [
${devProjects.map(p => formatProjectObject(p)).join(',\n')}
];
`;

// Generate design.ts
const designContent = `// This file is auto-generated by scripts/generate-projects.cjs
// Do not edit this file directly.
// Edit the markdown files in public/projects/ instead.

import { Project } from '../../types';

export const DESIGN_DATA: Project[] = [
${designProjects.map(p => formatProjectObject(p)).join(',\n')}
];
`;

fs.writeFileSync(OUTPUT_DEV_FILE, devContent);
fs.writeFileSync(OUTPUT_DESIGN_FILE, designContent);

console.log(`Successfully generated ${devProjects.length} dev projects to ${OUTPUT_DEV_FILE}`);
console.log(`Successfully generated ${designProjects.length} design projects to ${OUTPUT_DESIGN_FILE}`);
