const fs = require('fs');
const path = require('path');
const matter = require('gray-matter');
const crypto = require('crypto');

const ARTICLES_DIR = path.join(__dirname, '../public/articles');
const OUTPUT_FILE = path.join(__dirname, '../src/data/generated_articles.ts');

// Ensure articles directory exists
if (!fs.existsSync(ARTICLES_DIR)) {
  console.error(`Directory not found: ${ARTICLES_DIR}`);
  process.exit(1);
}

// Helper to generate MD5 ID
function generateId(content) {
  return crypto.createHash('md5').update(content).digest('hex');
}

const CATEGORY_MAP = {
  'DiT': 'DiT',
  'LUNA': 'LUNA',
  'Talk': '瞎叨be叨',
  'After8': 'After8',
  'Serenity': '山海疗养院',
  // Variations
  'talk': '瞎叨be叨',
  'dit': 'DiT',
  'luna': 'LUNA',
  'after8': 'After8',
  'serenity': '山海疗养院'
};

const DEFAULT_CATEGORY = '瞎叨be叨';

function scanArticles() {
  const files = fs.readdirSync(ARTICLES_DIR);
  const articles = [];

  files.forEach(file => {
    if (!file.endsWith('.md')) return;

    const filePath = path.join(ARTICLES_DIR, file);
    const fileContent = fs.readFileSync(filePath, 'utf8');
    const { data } = matter(fileContent);

    // Skip if draft
    if (data.draft) return;

    // Generate ID based on filename (stable ID) or content
    // Using filename is better for stability if content changes but it's the same article
    const id = generateId(file);

    // Determine if local or external
    let isLocal = !data.link;
    let link = data.link || `/articles/${file}`;

    // Force 'wechat' tagged articles to be treated as external
    if (data.tags && data.tags.includes('wechat')) {
      isLocal = false;
    }

    // Handle title (bilingual support)
    const titleZh = data.title || 'Untitled';
    const titleEn = data.title_en || titleZh;

    // Handle Category Mapping
    let category = data.category || 'Talk';
    if (CATEGORY_MAP[category]) {
      category = CATEGORY_MAP[category];
    } else {
      // Check if it matches one of the values directly (e.g. user used the Chinese enum value)
      const validValues = Object.values(CATEGORY_MAP);
      if (!validValues.includes(category)) {
        console.warn(`Warning: Unknown category '${category}' in ${file}. Defaulting to '${DEFAULT_CATEGORY}'.`);
        category = DEFAULT_CATEGORY;
      }
    }

    // Construct article object matching the structure in src/data/articles.ts
    // We need to match the structure expected by constants.ts and ArticleSection.tsx
    // The current structure in articles.ts is:
    // { id, common: { category, link, date, isLocal, tags, coverImage }, zh: { title }, en: { title } }

    const article = {
      id: id,
      common: {
        category: category,
        link: link,
        date: data.date ? new Date(data.date).toISOString().split('T')[0] : '',
        isLocal: isLocal,
        tags: data.tags || [],
        coverImage: data.coverImage || undefined,
        star: data.star || false
      },
      zh: {
        title: titleZh
      },
      en: {
        title: titleEn
      }
    };

    articles.push(article);
  });

  // Sort by date descending
  articles.sort((a, b) => {
    const dateA = new Date(a.common.date || 0);
    const dateB = new Date(b.common.date || 0);
    return dateB - dateA;
  });

  return articles;
}

const articles = scanArticles();

const fileContent = `// This file is auto-generated by scripts/generate-articles.cjs
// Do not edit this file directly.
// Edit the markdown files in public/articles/ instead.

import { ArticleCategory, Language } from '../../types';

export interface ArticlesPageContent {
  title: string;
  description: string;
}

export const ARTICLES_PAGE_DATA: Record<Language, ArticlesPageContent> = {
  zh: {
    title: '文章',
    description: '个人思考、学习分享与生活记录。'
  },
  en: {
    title: 'Articles',
    description: 'Thoughts, learning journey, and life records.'
  }
};

export const ARTICLE_DATA = ${JSON.stringify(articles, null, 2)};
`;

// We need to fix the JSON stringify to use the Enum values if we want to be strict,
// but since the Enum values are strings ('DiT', 'LUNA', etc.), 
// and the frontmatter should provide these strings, it should work fine as long as 
// the frontmatter values match the Enum values.
// However, to make it cleaner in TS, we might want to cast the category string.
// But JSON.stringify will output strings.
// In types.ts: export enum ArticleCategory { DIT = 'DiT', ... }
// So if data.category is 'DiT', it matches the enum value.

fs.writeFileSync(OUTPUT_FILE, fileContent);

console.log(`Successfully generated ${articles.length} articles to ${OUTPUT_FILE}`);
